/**
 * Returns the deterministic Quran reflection for any day 1..365.
 * Uses the curated core database and a deterministic mapped generator for the full 365 days.
 */
export function getQuranReflectionForDay(dayOfYear: number): QuranReflection {
  const normalizedDay = Math.max(1, Math.min(365, Math.floor(dayOfYear) || 1));
  const coreMatch = CORE_QURAN_COLLECTION.find((q) => q.dayNumber === normalizedDay);
  if (coreMatch) {
    return coreMatch;
  }

  // Deterministically cycle and derive from rich canonical collection with day-specific identity
  const baseIndex = (normalizedDay - 1) % CORE_QURAN_COLLECTION.length;
  const baseItem = CORE_QURAN_COLLECTION[baseIndex];

  return {
    ...baseItem,
    dayNumber: normalizedDay,
    theme: `${baseItem.theme} • দিন ${normalizedDay}`,
  };
}
