export function getHadithReflectionForDay(dayOfYear: number): HadithReflection {
  const normalizedDay = Math.max(1, Math.min(365, Math.floor(dayOfYear) || 1));
  const coreMatch = CORE_HADITH_COLLECTION.find((h) => h.dayNumber === normalizedDay);
  if (coreMatch) {
    return coreMatch;
  }

  // Deterministically cycle through the canonical collection
  const baseIndex = (normalizedDay - 1) % CORE_HADITH_COLLECTION.length;
  const baseItem = CORE_HADITH_COLLECTION[baseIndex];

  return {
    ...baseItem,
    dayNumber: normalizedDay,
    theme: `${baseItem.theme} • দিন ${normalizedDay}`,
  };
}
