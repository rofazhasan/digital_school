def enrich_topics():
    total_files = 0
    for filename, topic_plan in CHAPTER_GRANULAR_MATH_TOPICS.items():
        filepath = os.path.join(BASE_DIR, filename)
        if not os.path.exists(filepath):
            continue

        wb = openpyxl.load_workbook(filepath)
        ws = wb['Template'] if 'Template' in wb.sheetnames else wb.active

        # Build list of 50 topics according to plan
        math_topic_list = []
        for top_name, count in topic_plan:
            math_topic_list.extend([top_name] * count)

        # Truncate or pad to exactly 50 if needed
        math_topic_list = math_topic_list[:50]
        while len(math_topic_list) < 50:
            math_topic_list.append(topic_plan[-1][0])

        # Assign to rows 52-101 (Column 4)
        for idx, top_name in enumerate(math_topic_list):
            row_num = 52 + idx
            ws.cell(row=row_num, column=4, value=top_name)

        wb.save(filepath)
        total_files += 1
        distinct_count = len(set(math_topic_list))
        print(f"[ENRICHED] {filename} -> 50 Math questions mapped to {distinct_count} granular syllabus subtopics.")

    print(f"\nSuccessfully enriched all {total_files} workbooks with complete syllabus subtopic granularity!")

if __name__ == '__main__':
    enrich_topics()
